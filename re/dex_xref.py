#!/usr/bin/env python3
"""DEX call-graph for JNI bridge methods: who calls native<X> and with which string constants.
Usage: dex_xref.py classes8.dex nativeValidate nativeSnapshot|...
"""
import sys, struct
path=sys.argv[1]; targets=set(sys.argv[2:])
d=open(path,'rb').read()
def u32(o): return struct.unpack_from('<I',d,o)[0]
def u16(o): return struct.unpack_from('<H',d,o)[0]
def uleb(o):
    r=0;sh=0
    while True:
        b=d[o];o+=1;r|=(b&0x7f)<<sh;sh+=7
        if b<0x80:return r,o
def sleb(o):
    r=0;sh=0
    while True:
        b=d[o];o+=1;r|=(b&0x7f)<<sh;sh+=7
        if b<0x80:
            if b&0x40: r-=1<<sh
            return r,o
ssz,soff=u32(56),u32(60)
tsz,toff=u32(64),u32(68)
psz,poff=u32(72),u32(76)
fsz,foff=u32(80),u32(84)
msz,moff=u32(88),u32(92)
csz,coff=u32(96),u32(100)
strs=[]
for i in range(ssz):
    o=u32(soff+4*i); n,o2=uleb(o); strs.append(d[o2:o2+n].decode('utf-8','replace'))
def tname(i):
    s=u32(toff+4*i); return strs[s]
def mname(mi):
    c=u16(moff+8*mi); n=u32(moff+8*mi+4); return tname(c).rsplit('/',1)[-1].rstrip(';')+'.'+strs[n]
names=[mname(i) for i in range(msz)]
tgt_ids={i for i,n in enumerate(names) if n.split('.',1)[1] in targets or n.split('.',1)[1] in {t for t in targets}}
callers={i:[] for i in tgt_ids}
# iterate classes
for ci in range(csz):
    b=coff+32*ci
    cidx=u32(b); cd=u32(b+24)
    cn=tname(cidx).rsplit('/',1)[-1].rstrip(';')
    if cd==0: continue
    p=cd
    sf,p=uleb(p); inf,p=uleb(p); dm,p=uleb(p); vm,p=uleb(p)
    fidx=0
    for cnt in (sf,inf):
        for _ in range(cnt):
            di,p=uleb(p); ai,p=uleb(p); fidx+=di
    midx=-1
    for cnt in (dm,vm):
        for _ in range(cnt):
            di,p=uleb(p); ai,p=uleb(p); code,p=uleb(p); midx+=di
            cname=names[midx].split('.',1)[1] if 0<=midx<msz else '?'
            if code==0: continue
            insns=u32(code+12)
            q=code+16
            for _ in range(insns):
                w=u16(q)
                op=w&0xff
                if op in (0x6e,0x6f,0x70,0x71,0x72,0x74,0x75,0x76,0x77):
                    if op in (0x74,0x75,0x76,0x77): ln=3; mi=u16(q+2)
                    else: ln=2; mi=u16(q+2)
                    if mi in tgt_ids: callers[mi].append((cn,cname))
                elif op==0x18: ln=5
                elif op in (0x19,): ln=2
                elif op in (0x1a,0x1c,0x1f,0x20,0x22,0x23,0xfe,0xff): ln=2
                elif op in (0x1b,0x1d,0x21,0x24,0x25,0x26,0x2a,0x2b,0x2c,0xfc,0xfd): ln=3
                elif op==0x1e: ln=2
                elif op in (0x27,0x28,0x29): ln=3
                elif op==0x2d: ln=2
                elif op in (0x2e,0x2f,0x30): ln=3
                elif op in (0x31,0x32,0x33): ln=3
                elif op in (0x34,0x35,0x36,0x37): ln=3
                elif op in (0x38,0x39,0x3a): ln=3
                elif op in (0x3b,0x3c,0x3d,0x3e,0x3f,0x40,0x41,0x42,0x43,0x44): ln=2
                elif op==0x45: ln=3
                elif op in (0x46,0x47,0x48,0x49,0x4a): ln=3
                elif op in (0x4b,0x4c,0x4d,0x4e,0x4f,0x50,0x51,0x52): ln=3
                elif op in (0x53,0x54,0x55,0x56,0x57,0x58): ln=3
                elif op in (0x59,0x5a,0x5b,0x5c,0x5d,0x5e,0x5f): ln=3
                elif op in (0x60,0x61,0x62,0x63,0x64,0x65,0x66): ln=2
                elif op in (0x67,0x68,0x69,0x6a,0x6b,0x6c,0x6d): ln=3
                elif op in (0x73,): ln=1
                elif op in (0x79,0x7a,0x7c,0x7d,0x7e,0x7f,0x80,0x81,0x82,0x83,0x90,0x91,0x92,0x93,0x94,0x95,0x96,0xa0,0xa1,0xa2,0xa3,0xa4,0xa5,0xa6,0xab,0xac,0xad,0xae,0xaf,0xb0,0xb1,0xb2,0xb3,0xbb,0xbc,0xbd,0xbe,0xbf,0xc0,0xc1,0xd0,0xd1,0xd2,0xd3,0xd4,0xd5,0xd6,0xd7,0xd8): ln=2
                elif op in (0x84,0x85,0x86,0x87,0x88,0x89,0x8a,0x8b,0x8c,0x8d,0x8e,0x8f,0x97,0x98,0x99,0x9a,0x9b,0x9c,0x9d,0x9e,0x9f,0xa7,0xa8,0xa9,0xaa,0xb4,0xb5,0xb6,0xb7,0xb8,0xb9,0xba,0xc2,0xc3,0xc4,0xc5,0xc6,0xc7,0xc8,0xc9,0xca,0xcb,0xcc,0xcd,0xce,0xcf): ln=1
                elif op in (0x0e,0x0f,0x10,0x11,0x1d,0x1e,0x27,0x28,0x29): ln=1
                elif op in (0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0b,0x0c,0x0d,0x0a,0x12,0x13,0x14,0x15,0x16,0x17): ln=1
                elif op in (0xf0,0xf1,0xf2,0xf3,0xf4,0xf5,0xf6,0xf7,0xf8,0xf9,0xfa,0xfb): ln=2
                elif op==0x1a: ln=2
                elif op in (0x78,0x98): ln=2
                elif op==0x25: ln=3
                else: ln=1
                q+=ln
            if q>code+16+insns*4: pass
for mi in sorted(tgt_ids):
    print(f'\n## {names[mi]}  -> {len(callers[mi])} callers')
    for c,m in callers[mi][:25]:
        print(f'   {c}.{m}')
